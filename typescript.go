// TypeScript returns TypeScript interfaces for every registered resource's model and the
// models its relations point to. The output matches what the API sends: the same JSON
// names, times as ISO strings, pointers as "| null", omitempty fields (relations) optional.
func (p *Panel) TypeScript() string {
	g := &tsGen{names: map[reflect.Type]string{}, taken: map[string]bool{}}
	resourceTypes := make([]string, 0, len(p.names()))
	for _, name := range p.names() {
		t := reflect.TypeOf(p.mustLookup(name).res.newModel()).Elem()
		resourceTypes = append(resourceTypes, fmt.Sprintf("  %s: %s", tsKey(name), g.typeName(t)))
	}

	var b strings.Builder
	b.WriteString("// Code generated by the panel. DO NOT EDIT.\n")
	b.WriteString("// Source: the Go models of the registered resources.\n\n")
	for i := 0; i < len(g.queue); i++ { // the queue grows while emitting
		g.emit(&b, g.queue[i])
	}
	b.WriteString("/** Record type of each resource, by resource name. */\n")
	b.WriteString("export interface Resources {\n")
	b.WriteString(strings.Join(resourceTypes, "\n"))
	b.WriteString("\n}\n")
	return b.String()
}

type tsGen struct {
	names map[reflect.Type]string
	taken map[string]bool
	queue []reflect.Type
}

// typeName returns the interface name for a struct type, scheduling it for output.
func (g *tsGen) typeName(t reflect.Type) string {
	if name, ok := g.names[t]; ok {
		return name
	}
	base := t.Name()
	if base == "" {
		base = "Anonymous"
	}
	base = strings.ToUpper(base[:1]) + base[1:]
	name := base
	for i := 2; g.taken[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	g.taken[name] = true
	g.names[t] = name
	g.queue = append(g.queue, t)
	return name
}

func (g *tsGen) emit(b *strings.Builder, t reflect.Type) {
	fmt.Fprintf(b, "export interface %s {\n", g.names[t])
	for _, f := range orderedFields(t) {
		optional := ""
		if f.omitempty {
			optional = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s\n", tsKey(f.name), optional, g.tsType(f.typ))
	}
	b.WriteString("}\n\n")
}

func (g *tsGen) tsType(t reflect.Type) string {
	if t.Kind() == reflect.Pointer {
		if isTimeType(t) {
			return "string | null"
		}
		return g.tsType(t.Elem()) + " | null"
	}
	if isTimeType(t) {
		return "string"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string" // []byte is base64 in JSON
		}
		elem := t.Elem()
		if elem.Kind() == reflect.Pointer && !isTimeType(elem) {
			elem = elem.Elem() // []*Tag holds no nulls in practice
		}
		inner := g.tsType(elem)
		if strings.Contains(inner, " ") {
			inner = "(" + inner + ")"
		}
		return inner + "[]"
	case reflect.Map:
		return "Record<string, " + g.tsType(t.Elem()) + ">"
	case reflect.Struct:
		if t.Implements(jsonTypedType) {
			// mks.JSON[T]: describe T itself.
			return g.tsType(reflect.Zero(t).Interface().(jsonTyped).panelJSONType())
		}
		if t.Implements(marshalerType) || reflect.PointerTo(t).Implements(marshalerType) {
			return "unknown" // custom JSON: shape unknown
		}
		return g.typeName(t)
	}
	return "unknown"
}

type tsField struct {
	name      string
	typ       reflect.Type
	omitempty bool
}

// orderedFields lists JSON fields in declaration order, inlining embedded structs.
func orderedFields(t reflect.Type) []tsField {
	var out []tsField
	seen := map[string]int{}
	var walk func(t reflect.Type)
	walk = func(t reflect.Type) {
		for i := range t.NumField() {
			f := t.Field(i)
			if f.Anonymous && f.Tag.Get("json") == "" && f.Type.Kind() == reflect.Struct && !isTimeType(f.Type) {
				walk(f.Type)
				continue
			}
			if !f.IsExported() {
				continue
			}
			name, omitempty, skip := jsonName(f)
			if skip {
				continue
			}
			field := tsField{name: name, typ: f.Type, omitempty: omitempty}
			if idx, dup := seen[name]; dup {
				out[idx] = field // outer field wins, like encoding/json
				continue
			}
			seen[name] = len(out)
			out = append(out, field)
		}
	}
	walk(t)
	return out
}

var tsIdentifier = func(s string) bool {
	for i, r := range s {
		if !(r == '_' || r == '$' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9') {
			return false
		}
	}
	return s != ""
}

func tsKey(name string) string {
	if tsIdentifier(name) {
		return name
	}
	quoted, _ := json.Marshal(name)
	return string(quoted)
}

// --- artisan command ----------------------------------------------------------------------

// TypesCommand is an artisan command that writes TypeScript() to a file. The panel is
// built lazily, because commands are registered before the application has booted.
// Register it with WithCommands, e.g. mks.TypesCommand(admin.Panel, "admin/types.generated.ts").
func TypesCommand(panel func() *Panel, defaultOutput string) console.Command {
	return &typesCommand{panel: panel, output: defaultOutput}
}

type typesCommand struct {
	panel  func() *Panel
	output string
}

func (c *typesCommand) Signature() string { return "mks:types" }

func (c *typesCommand) Description() string {
	return "Generate TypeScript types for the admin panel resources"
}

func (c *typesCommand) Extend() command.Extend {
	return command.Extend{
		Category: "mks",
		Flags: []command.Flag{
			&command.StringFlag{Name: "output", Aliases: []string{"o"}, Value: c.output, Usage: "file to write"},
		},
	}
}

func (c *typesCommand) Handle(ctx console.Context) error {
	out := ctx.Option("output")
	if out == "" {
		out = c.output
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(out, []byte(c.panel().TypeScript()), 0o644); err != nil {
		return err
	}
	ctx.Info("Wrote " + out)
	return nil
}
